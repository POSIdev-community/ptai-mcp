import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { MCP_PACKAGE_NAME } from './launch.js';
import { getRulesContent } from './rules.js';

const execFileAsync = promisify(execFile);
type CommandRunner = (file: string, args: readonly string[]) => Promise<unknown>;

export const CUSTOM_AGENT_ID = '__custom_agent__';

export function getCustomAgentGuidePath(): string {
  return path.join(os.homedir(), '.ptai-mcp', 'PT_AI_Custom_Agent_Setup.md');
}

export async function writeCustomAgentGuide(guidePath = getCustomAgentGuidePath()): Promise<string> {
  await fs.mkdir(path.dirname(guidePath), { recursive: true });
  await fs.writeFile(guidePath, customAgentGuide(), 'utf8');
  return guidePath;
}

export async function removeCustomAgentGuide(guidePath = getCustomAgentGuidePath()): Promise<boolean> {
  try {
    await fs.unlink(guidePath);
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false;
    throw error;
  }
}

export async function openCustomAgentGuide(run: CommandRunner = execFileAsync): Promise<void> {
  const guidePath = getCustomAgentGuidePath();
  if (process.platform === 'win32') {
    await run('rundll32.exe', ['url.dll,FileProtocolHandler', guidePath]);
  } else if (process.platform === 'darwin') {
    await run('open', [guidePath]);
  } else {
    await run('xdg-open', [guidePath]);
  }
}

export function customAgentGuide(): string {
  return `# PT AI MCP: custom agent setup

This guide is generated by \`${MCP_PACKAGE_NAME}\`. Adapt the examples to the configuration format supported by your agent.

## MCP server

Configure an MCP server named \`ptai_analyzer\`:

\`\`\`json
{
  "mcpServers": {
    "ptai_analyzer": {
      "command": "npx",
      "args": ["-y", "${MCP_PACKAGE_NAME}", "start"]
    }
  }
}
\`\`\`

If your agent expects the OpenCode-style local command array, use:

\`\`\`json
{
  "mcp": {
    "ptai_analyzer": {
      "type": "local",
      "command": ["npx", "-y", "${MCP_PACKAGE_NAME}", "start"],
      "enabled": true,
      "timeout": 600000
    }
  }
}
\`\`\`

## Hooks

If the agent supports lifecycle hooks, call these commands and pass the agent hook payload through stdin as JSON:

- before a user prompt: \`npx -y ${MCP_PACKAGE_NAME} start hook-start --format plain\`
- when the agent is about to finish: \`npx -y ${MCP_PACKAGE_NAME} start hook --format plain\`

Available formats: \`plain\`, \`json\`, \`cursor\`, \`windsurf\`, \`kimi\`, \`claude-code\`, \`opencode\`.

The stop hook returns exit code \`2\` when findings must be fixed. In that case, feed its output back to the agent and repeat no more than twice per response.

## Agent rules

Add the following rules to the agent's global instruction file:

${getRulesContent()}
`;
}
