import fs from 'node:fs/promises';
import path from 'node:path';
import type { AgentDefinition } from './registry.js';
import { MCP_SERVER_NAME } from './constants.js';
import { MCP_PACKAGE_NAME } from './launch.js';
import { getRulesContent } from './rules.js';
import { parseJsonc, updateJsoncPropertyPath } from '../utils/jsonc.js';

const PLUGIN_MARKER = '// Generated by @posidev-community/ptai-mcp. Do not edit.';

export async function configureOpenCodeMcp(configPath: string) {
  const source = await readOptional(configPath);
  const desired = {
    type: 'local',
    command: ['npx', '-y', MCP_PACKAGE_NAME, 'start'],
    disabled: false,
    timeout: {
      startup: 600000,
      catalog: 600000,
      execution: 600000,
    },
  };
  const configured = updateJsoncPropertyPath(source ?? '{}\n', ['mcp', 'servers', MCP_SERVER_NAME], desired);
  // Remove the pre-V2 location after migrating it to mcp.servers.
  const updated = updateJsoncPropertyPath(configured, ['mcp', MCP_SERVER_NAME], undefined);
  const changed = updated !== (source ?? '{}\n');
  if (changed) await writeText(configPath, updated);
  return { changed, paths: [configPath] };
}

export async function removeOpenCodeMcp(configPath: string): Promise<boolean> {
  const source = await readOptional(configPath);
  if (source === null) return false;
  const withoutV2 = updateJsoncPropertyPath(source, ['mcp', 'servers', MCP_SERVER_NAME], undefined);
  const updated = updateJsoncPropertyPath(withoutV2, ['mcp', MCP_SERVER_NAME], undefined);
  if (updated === source) return false;
  await writeText(configPath, updated);
  return true;
}

export async function isOpenCodeMcpConfigured(configPath: string): Promise<boolean> {
  const source = await readOptional(configPath);
  if (source === null) return false;
  try {
    const model = parseJsonc(source);
    const mcp = asRecord(model.mcp);
    const servers = asRecord(mcp?.servers);
    const server = asRecord(servers?.[MCP_SERVER_NAME]);
    const command = server?.command;
    return (
      server?.type === 'local' &&
      Array.isArray(command) &&
      command.includes(MCP_PACKAGE_NAME) &&
      command.includes('start')
    );
  } catch {
    return false;
  }
}

export async function configureOpenCodeHooks(agent: AgentDefinition, proxyPath: string): Promise<boolean> {
  const pluginPath = agent.getHooksConfigPaths()[0];
  const desired = openCodePlugin(proxyPath);
  const existing = await readOptional(pluginPath);

  const mcpConfigPath = agent.getMcpConfigPaths()[0];
  if (mcpConfigPath) {
    const configSource = await readOptional(mcpConfigPath);
    let updatedConfig = configSource ?? '{}\n';
    const pluginDir = path.dirname(pluginPath).replace(/\\/g, '/');
    try {
      const model = parseJsonc(updatedConfig);
      const pluginsArray = Array.isArray(model.plugins) ? model.plugins : [];
      if (!pluginsArray.includes(pluginDir)) {
        updatedConfig = updateJsoncPropertyPath(updatedConfig, ['plugins'], [
          ...pluginsArray,
          pluginDir,
        ] as unknown as Record<string, unknown>);
        await writeText(mcpConfigPath, updatedConfig);
      }
    } catch {
      /* ignore */
    }
  }
  if (existing === desired) return false;
  if (existing !== null && !existing.startsWith(PLUGIN_MARKER)) {
    throw new Error(`Refusing to overwrite an existing OpenCode plugin not managed by PTAI: ${pluginPath}`);
  }
  await writeText(pluginPath, desired);
  return true;
}

export async function isOpenCodeHooksConfigured(agent: AgentDefinition): Promise<boolean> {
  return (await readOptional(agent.getHooksConfigPaths()[0]))?.startsWith(PLUGIN_MARKER) ?? false;
}

export async function removeOpenCodeHooks(agent: AgentDefinition): Promise<boolean> {
  const pluginPath = agent.getHooksConfigPaths()[0];
  const source = await readOptional(pluginPath);
  if (!source?.startsWith(PLUGIN_MARKER)) return false;
  await fs.unlink(pluginPath);
  try {
    await fs.rmdir(path.dirname(pluginPath));
  } catch {
    /* ignore */
  }

  const mcpConfigPath = agent.getMcpConfigPaths()[0];
  if (mcpConfigPath) {
    const configSource = await readOptional(mcpConfigPath);
    if (configSource) {
      const pluginDir = path.dirname(pluginPath).replace(/\\/g, '/');
      try {
        const model = parseJsonc(configSource);
        if (Array.isArray(model.plugins)) {
          const newPlugins = model.plugins.filter((p: unknown) => p !== pluginDir);
          if (newPlugins.length !== model.plugins.length) {
            const updatedConfig = updateJsoncPropertyPath(
              configSource,
              ['plugins'],
              newPlugins.length > 0 ? (newPlugins as unknown as Record<string, unknown>) : undefined,
            );
            await writeText(mcpConfigPath, updatedConfig);
          }
        }
      } catch {
        /* ignore */
      }
    }
  }

  return true;
}

export function openCodePlugin(proxyPath: string): string {
  const rules = getRulesContent();
  return `${PLUGIN_MARKER}
import { spawn } from "node:child_process"

const PROXY_PATH = ${JSON.stringify(proxyPath)}
const SECURITY_RULES = ${JSON.stringify(rules)}
const MAX_IDLE_ATTEMPTS = 2

function runProxy(args: string[], stdin: string): Promise<{ exitCode: number | null; stdout: string; stderr: string }> {
  return new Promise((resolve, reject) => {
    const child = spawn(PROXY_PATH, args, { stdio: ["pipe", "pipe", "pipe"] })
    let stdout = ""
    let stderr = ""
    child.stdout.on("data", (chunk: Buffer) => { stdout += chunk })
    child.stderr.on("data", (chunk: Buffer) => { stderr += chunk })
    child.on("error", reject)
    child.on("close", (exitCode) => resolve({ exitCode, stdout, stderr }))
    child.stdin.end(stdin)
  })
}

export default {
  id: "ptai-security",
  async setup(ctx) {
    const idleAttempts = new Map<string, number>()
    const activeSessions = new Set<string>()
    const registrations: Array<{ dispose(): Promise<void> }> = []
    const controller = new AbortController()
    const hookInput = (sessionID?: string) => JSON.stringify({
      workspace_roots: [ctx.location.directory],
      session_id: sessionID,
      stop_hook_active: false,
    })

    registrations.push(await ctx.session.hook("chat.message", async (event) => {
      activeSessions.add(event.sessionID)
      await runProxy(["hook-start", "--format", "opencode"], hookInput(event.sessionID)).catch(() => undefined)
    }))

    registrations.push(await ctx.session.hook("context", (event) => {
      event.system.push({ type: "text", text: SECURITY_RULES })
    }))

    void (async () => {
      try {
        for await (const event of ctx.event.subscribe({ signal: controller.signal })) {
          if (event.type === "session.deleted") {
            const sessionID = event.properties.info.id
            activeSessions.delete(sessionID)
            idleAttempts.delete(sessionID)
            continue
          }
          if (event.type !== "session.idle") continue

          const sessionID = event.properties.sessionID
          if (!activeSessions.has(sessionID)) continue
          const count = idleAttempts.get(sessionID) ?? 0
          if (count >= MAX_IDLE_ATTEMPTS) continue

          const result = await runProxy(["hook", "--format", "opencode"], hookInput(sessionID)).catch(() => null)
          if (!result || result.exitCode !== 2) {
            idleAttempts.delete(sessionID)
            continue
          }

          idleAttempts.set(sessionID, count + 1)
          const report = result.stdout.trim() || result.stderr.trim()
          await ctx.session.prompt({
            sessionID,
            text: \`Security gate failed (attempt \${count + 1}/\${MAX_IDLE_ATTEMPTS}).\\n\${report}\\nFix the findings and do not finish until all issues are resolved.\`,
          })
        }
      } catch (error) {
        if (!controller.signal.aborted) console.error("PT AI event subscription failed", error)
      }
    })()

    return async () => {
      controller.abort()
      await Promise.all(registrations.map((registration) => registration.dispose()))
    }
  },
}
`;
}

async function readOptional(filePath: string): Promise<string | null> {
  try {
    return await fs.readFile(filePath, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw error;
  }
}

async function writeText(filePath: string, content: string): Promise<void> {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content, 'utf8');
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : undefined;
}
